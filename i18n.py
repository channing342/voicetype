    """{內部代碼: 字串 key} 的唯讀對照，取值時依目前語系翻譯（MODE_NAMES 這類常數用）。"""

    def __init__(self, keys):
        self.keys_ = dict(keys)

    def __getitem__(self, code):
        return t(self.keys_[code])

    def __iter__(self):
        return iter(self.keys_)

    def __len__(self):
        return len(self.keys_)
