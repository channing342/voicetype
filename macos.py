"""macOS 系統互動：剪貼簿貼上、讀取選取文字、目前 App 與視窗資訊。"""
import subprocess
import time

import objc
from AppKit import NSPasteboard, NSPasteboardItem, NSPasteboardTypeString, NSWorkspace
import ApplicationServices as AX
import Quartz

from core import KEY_C, KEY_RETURN, KEY_V

# nspasteboard.org 慣例：剪貼簿管理器（Raycast、Paste、Maccy…）看到這些類型就不記錄
MARKER_TYPES = ("org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType")


def _press(keycode, flags=Quartz.kCGEventFlagMaskCommand):
    for down in (True, False):
        ev = Quartz.CGEventCreateKeyboardEvent(None, keycode, down)
        Quartz.CGEventSetFlags(ev, flags)  # 明確設定，使用者還按著 Shift 也不會變成 ⇧⌘V 或 ⇧Enter
        Quartz.CGEventPost(Quartz.kCGHIDEventTap, ev)


def press_return():
    _press(KEY_RETURN, 0)


def _snapshot(pb):
    return [{t: item.dataForType_(t) for t in item.types()} for item in (pb.pasteboardItems() or [])]


def _restore(pb, saved):
    pb.clearContents()
    items = []
    for d in saved:
        item = NSPasteboardItem.alloc().init()
        for t, data in d.items():
            if data is not None:
                item.setData_forType_(data, t)
        for t in MARKER_TYPES:  # 還原的是使用者原本就有的內容，不要讓管理器再記一次
            item.setString_forType_("", t)
        items.append(item)
    if items:
        pb.writeObjects_(items)


def paste(text):
    """備份剪貼簿 → 放入文字（標記為暫時）→ ⌘V → 還原剪貼簿（含圖片等非文字內容）。"""
    pb = NSPasteboard.generalPasteboard()
    saved = _snapshot(pb)
    pb.clearContents()
    item = NSPasteboardItem.alloc().init()
    item.setString_forType_(text, NSPasteboardTypeString)
    for t in MARKER_TYPES:
        item.setString_forType_("", t)
    pb.writeObjects_([item])
    _press(KEY_V)
    time.sleep(0.3)  # ponytail: 固定等待讓目標 App 讀完剪貼簿，極慢的 App 可能需要調大
    _restore(pb, saved)


def copy_text(text, transient=False):
    """transient=True 時剪貼簿管理器不會記錄（選取翻譯的「複製」用）。"""
    pb = NSPasteboard.generalPasteboard()
    pb.clearContents()
    item = NSPasteboardItem.alloc().init()
    item.setString_forType_(text, NSPasteboardTypeString)
    for t in MARKER_TYPES if transient else ():
        item.setString_forType_("", t)
    pb.writeObjects_([item])


def clipboard_text():
    return NSPasteboard.generalPasteboard().stringForType_(NSPasteboardTypeString) or ""


def _ax(element, attr):
    err, value = AX.AXUIElementCopyAttributeValue(element, attr, None)
    return value if err == 0 else None


def focused_element(app=None):
    """實測 macOS 27 的 system-wide 查詢常回 -25204（kAXErrorCannotComplete），改問最前面的 App 就拿得到。"""
    el = None if app else _ax(AX.AXUIElementCreateSystemWide(), AX.kAXFocusedUIElementAttribute)
    if el is None:
        app = app or NSWorkspace.sharedWorkspace().frontmostApplication()
        el = _ax(AX.AXUIElementCreateApplication(app.processIdentifier()), AX.kAXFocusedUIElementAttribute)
    return el


def read_selection(allow_copy=True):
    """優先用輔助使用 API；讀不到（部分 Electron App）且 allow_copy 時才用 ⌘C，並還原剪貼簿。"""
    el = focused_element()
    text = _ax(el, AX.kAXSelectedTextAttribute) if el else None
    if text or not allow_copy:
        return str(text or "")
    pb = NSPasteboard.generalPasteboard()
    saved, count = _snapshot(pb), pb.changeCount()
    _press(KEY_C)
    for _ in range(10):
        time.sleep(0.03)
        if pb.changeCount() != count:
            break
    text = pb.stringForType_(NSPasteboardTypeString) if pb.changeCount() != count else ""
    if pb.changeCount() != count:
        _restore(pb, saved)
    return text or ""


def selection_bounds():
    """選取文字在螢幕上的位置 (x, y, w, h)，原點在主螢幕左上角；App 不支援時回傳 None。"""
    el = focused_element()
    rng = _ax(el, AX.kAXSelectedTextRangeAttribute) if el else None
    if rng is None:
        return None
    err, value = AX.AXUIElementCopyParameterizedAttributeValue(
        el, AX.kAXBoundsForRangeParameterizedAttribute, rng, None)
    if err:
        return None
    ok, rect = AX.AXValueGetValue(value, AX.kAXValueCGRectType, None)
    if not ok or rect.size.height <= 0:
        return None
    return rect.origin.x, rect.origin.y, rect.size.width, rect.size.height


def frontmost_context(include_input=False):
    """回傳 {app, bundle, title[, input_field]}；讀不到的欄位留空。"""
    app = NSWorkspace.sharedWorkspace().frontmostApplication()
    ctx = {"app": app.localizedName() or "", "bundle": app.bundleIdentifier() or "", "title": ""}
    win = _ax(AX.AXUIElementCreateApplication(app.processIdentifier()), AX.kAXFocusedWindowAttribute)
    if win is not None:
        ctx["title"] = str(_ax(win, AX.kAXTitleAttribute) or "")
    if include_input:
        el = focused_element()
        value = _ax(el, AX.kAXValueAttribute) if el else None
        ctx["input_field"] = str(value)[-2000:] if isinstance(value, str) else ""
    return ctx


# 系統設定 →「隱私權與安全性」各頁的網址
PRIVACY_PANES = {"accessibility": "Privacy_Accessibility", "input": "Privacy_ListenEvent",
                 "microphone": "Privacy_Microphone"}
_av = {}


def _capture_device():
    """AVFoundation 只為了查麥克風權限，用 loadBundle 載入就好，不另外裝 pyobjc-framework-AVFoundation。"""
    if not _av:
        objc.loadBundle("AVFoundation", _av, bundle_path="/System/Library/Frameworks/AVFoundation.framework")
    return _av["AVCaptureDevice"]


def permissions():
    """快捷鍵靠 event tap，要「輔助使用」；錄音要「麥克風」。麥克風還沒問過時是 None。"""
    mic = _capture_device().authorizationStatusForMediaType_("soun")  # 0 未決定、1 受限、2 拒絕、3 允許
    return {"accessibility": bool(AX.AXIsProcessTrusted()), "input": bool(Quartz.CGPreflightListenEventAccess()),
            "microphone": None if mic == 0 else mic == 3}


def request_permissions():
    """跳出系統的授權對話框（已允許或已拒絕過的不會再跳）。"""
    AX.AXIsProcessTrustedWithOptions({AX.kAXTrustedCheckOptionPrompt: True})
    Quartz.CGRequestListenEventAccess()
    if permissions()["microphone"] is None:
        _capture_device().requestAccessForMediaType_completionHandler_("soun", lambda granted: None)


def open_privacy(key):
    subprocess.run(["open", f"x-apple.systempreferences:com.apple.preference.security?{PRIVACY_PANES[key]}"])
